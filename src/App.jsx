function parseMarkdownToChangelog(markdown) {
  try {
    const lines = markdown.split('\n');
    const releases = [];
    let currentRelease = null;
    let currentSection = null;

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i].trim();

      const versionMatch = line.match(/^##\s+\[?v?([0-9]+\.[0-9]+\.[0-9]+)\]?\s*(?:-\s*([0-9]{4}-[0-9]{2}-[0-9]{2}))?/);
      if (versionMatch) {
        if (currentRelease) releases.push(currentRelease);
        currentRelease = {
          version: versionMatch[1],
          date: versionMatch[2] || 'Latest',
          isLatest: releases.length === 0,
          added: [],
          fixed: []
        };
        currentSection = null;
        continue;
      }

      if (!currentRelease) continue;

      if (line.startsWith('### Added')) {
        currentSection = 'added';
        continue;
      } else if (line.startsWith('### Fixed')) {
        currentSection = 'fixed';
        continue;
      } else if (line.startsWith('###')) {
        currentSection = 'added';
        continue;
      }

      if (currentSection && line.startsWith('- ')) {
        const itemText = line.substring(2).trim();
        const titleMatch = itemText.match(/^\*\*([^*]+)\*\*:\s*(.+)$/);
        if (titleMatch) {
          currentRelease[currentSection].push({
            title: titleMatch[1],
            desc: titleMatch[2]
          });
        } else {
          currentRelease[currentSection].push({
            title: itemText.split(':')[0] || 'Change',
            desc: itemText
          });
        }
      }
    }

    if (currentRelease) releases.push(currentRelease);
    return releases.length > 0 ? releases : null;
  } catch (err) {
    return null;
  }
}

